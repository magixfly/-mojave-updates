#!/usr/bin/env python3
"""web/car.html -> src/car_page.h (gzip, C array). Run before building: python3 tools/mkpage.py"""
import gzip, os
here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, "..", "web", "car.html")
dst = os.path.join(here, "..", "src", "car_page.h")
raw = open(src, "rb").read()
gz = gzip.compress(raw, 9, mtime=0)
lines = [", ".join("0x%02x" % b for b in gz[i:i + 20]) for i in range(0, len(gz), 20)]
with open(dst, "w") as f:
    f.write("// generated by tools/mkpage.py from web/car.html - do not edit\n#pragma once\n#include <stdint.h>\n")
    f.write("static const uint8_t CAR_PAGE[] = {\n" + ",\n".join(lines) + "\n};\n")
    f.write("static const size_t CAR_PAGE_LEN = %d;\n" % len(gz))
print("car_page.h: %d bytes html -> %d bytes gzip" % (len(raw), len(gz)))
